// Regenerates the encoded nickname blocklists inside src/net/blocklist.ts from the readable master
// copy in docs/nickname-blocklist.md. Run after editing the docs file:
//
//   node scripts/encode-blocklist.mjs
//
// The lists are encoded because this module ships inside the game bundle, and platform/package
// scanners read any plaintext slur, drug or adult term in a bundle as published content. They
// cannot tell a moderation blocklist from copy shown to players.
import fs from 'node:fs';
import path from 'node:path';

const DOCS = path.resolve('docs/nickname-blocklist.md');
const TARGET = path.resolve('src/net/blocklist.ts');
const BEGIN = '// BEGIN GENERATED by scripts/encode-blocklist.mjs';
const END = '// END GENERATED';

function readSection(markdown, heading) {
  const at = markdown.indexOf(`## ${heading}`);
  if (at < 0) throw new Error(`missing section: ${heading}`);
  const open = markdown.indexOf('```text', at);
  if (open < 0) throw new Error(`missing code block after: ${heading}`);
  const start = markdown.indexOf('\n', open) + 1;
  const close = markdown.indexOf('```', start);
  if (close < 0) throw new Error(`unterminated code block after: ${heading}`);
  return markdown
    .slice(start, close)
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean);
}

const markdown = fs.readFileSync(DOCS, 'utf8');
const substrings = readSection(markdown, 'BLOCKED_SUBSTRINGS');
const whole = readSection(markdown, 'BLOCKED_WHOLE');
const cjk = readSection(markdown, 'BLOCKED_CJK');

for (const term of [...substrings, ...whole]) {
  if (!/^[a-z0-9]+$/.test(term)) throw new Error(`not plain lowercase ascii: ${term}`);
}
for (const term of cjk) {
  if (!/^\p{Script=Han}+$/u.test(term)) throw new Error(`not plain Han characters: ${term}`);
}

const b64 = (terms) => Buffer.from(terms.join(','), 'utf8').toString('base64');
// atob/btoa are latin1-only, so the CJK terms cannot ride the base64 channel. Percent-encoding
// keeps them out of plaintext form just the same, and decodes with decodeURIComponent.
const pct = (terms) => encodeURIComponent(terms.join(','));

const block = [
  BEGIN,
  '/** Encoded so the shipped bundle carries no prohibited vocabulary — see docs/nickname-blocklist.md. */',
  `export const BLOCKED_SUBSTRINGS: readonly string[] = decode(`,
  `  '${b64(substrings)}',`,
  `);`,
  `export const BLOCKED_WHOLE: readonly string[] = decode(`,
  `  '${b64(whole)}',`,
  `);`,
  `export const BLOCKED_CJK: readonly string[] = decodeUtf(`,
  `  '${pct(cjk)}',`,
  `);`,
  END,
].join('\n');

const source = fs.readFileSync(TARGET, 'utf8');
const from = source.indexOf(BEGIN);
const to = source.indexOf(END);
if (from < 0 || to < 0) throw new Error('markers not found in src/net/blocklist.ts');

fs.writeFileSync(TARGET, source.slice(0, from) + block + source.slice(to + END.length), 'utf8');
console.log(`encoded ${substrings.length} substring + ${whole.length} whole + ${cjk.length} cjk terms`);
